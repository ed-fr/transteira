var update = flag.Bool("update", false, "rewrite the golden file")

var testCfg = config{pkg: "stubs", genImport: defaultGenImport}

func TestGenerateGolden(t *testing.T) {
	src, err := os.ReadFile(filepath.Join("testdata", "gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	got, err := generate("gen.go", src, testCfg)
	if err != nil {
		t.Fatal(err)
	}
	golden := filepath.Join("testdata", "stubs.golden")
	if *update {
		if err := os.WriteFile(golden, got, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(normalize(got), normalize(want)) {
		t.Errorf("output differs from %s (run go test -update):\n%s", golden, got)
	}
}

// TestRepositoryStubsUpToDate guards against a stale internal/api/stubs/stubs_gen.go.
func TestRepositoryStubsUpToDate(t *testing.T) {
	in := filepath.Join("..", "..", "internal", "api", "gen", "gen.go")
	src, err := os.ReadFile(in)
	if err != nil {
		t.Fatal(err)
	}
	got, err := generate(in, src, testCfg)
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile(filepath.Join("..", "..", "internal", "api", "stubs", "stubs_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(normalize(got), normalize(want)) {
		t.Error("internal/api/stubs/stubs_gen.go is out of date: run 'make generate'")
	}
}

func normalize(b []byte) []byte { return bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n")) }

const header = "package gen\n\nimport \"context\"\n\n"

// iface declares the strict interface with a single operation Op.
const iface = "type StrictServerInterface interface {\n\tOp(ctx context.Context, request OpRequestObject) (OpResponseObject, error)\n}\n" +
	"type OpRequestObject struct{}\ntype OpResponseObject interface{}\n"

func TestGenerateBodies(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want []string
		deny []string
	}{
		{
			name: "problem 404 response is not used",
			src:  header + iface + "type NotFoundApplicationProblemPlusJSONResponse struct{}\ntype Op404ApplicationProblemPlusJSONResponse struct{ NotFoundApplicationProblemPlusJSONResponse }\n",
			want: []string{"return nil, ErrNotImplemented", `"errors"`},
			deny: []string{"internal/api/problem", "404ApplicationProblemPlusJSONResponse"},
		},
		{
			name: "bodiless 404",
			src:  header + iface + "type Op404Response struct{}\n",
			want: []string{"return gen.Op404Response{}, nil", "var ErrNotImplemented = errors.New(\"stubs: operation not implemented\")"},
			deny: []string{"return nil, ErrNotImplemented"},
		},
		{
			name: "non-empty 404 response",
			src:  header + iface + "type Op404Response struct{ X int }\n",
			want: []string{"return nil, ErrNotImplemented"},
		},
		{
			name: "non-struct 404 response",
			src:  header + iface + "type Op404Response int\n",
			want: []string{"return nil, ErrNotImplemented"},
		},
		{
			name: "no 404 response",
			src:  header + iface,
			want: []string{"return nil, ErrNotImplemented"},
		},
		{
			name: "pointer and slice parameter types",
			src: header + "type StrictServerInterface interface {\n\tOp(ctx context.Context, r *OpRequestObject, s []string, u unexported) (OpResponseObject, error)\n}\n" +
				"type OpRequestObject struct{}\ntype OpResponseObject interface{}\ntype unexported int\n",
			want: []string{"func (Unimplemented) Op(_ context.Context, _ *gen.OpRequestObject, _ []string, _ unexported) (gen.OpResponseObject, error)"},
		},
		{
			name: "methods sorted by name",
			src: header + "type StrictServerInterface interface {\n\tZeta(ctx context.Context) (R, error)\n\tAlpha(ctx context.Context) (R, error)\n}\n" +
				"type R interface{}\n",
			want: []string{"Alpha(_ context.Context) (gen.R, error)", "Zeta(_ context.Context) (gen.R, error)"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			out, err := generate("gen.go", []byte(tt.src), testCfg)
			if err != nil {
				t.Fatal(err)
			}
			got := string(out)
			if !strings.HasPrefix(got, "// Code generated by genstubs. DO NOT EDIT.\n") {
				t.Error("missing generated header")
			}
			if !strings.Contains(got, "var _ gen.StrictServerInterface = Unimplemented{}") {
				t.Error("missing compile-time assertion")
			}
			for _, w := range tt.want {
				if !strings.Contains(got, w) {
					t.Errorf("output lacks %q:\n%s", w, got)
				}
			}
			for _, d := range tt.deny {
				if strings.Contains(got, d) {
					t.Errorf("output unexpectedly contains %q:\n%s", d, got)
				}
			}
			if tt.name == "methods sorted by name" && strings.Index(got, "Alpha") > strings.Index(got, "Zeta") {
				t.Error("methods are not sorted")
			}
		})
	}
}

func TestGenerateErrors(t *testing.T) {
	tests := []struct {
		name    string
		src     string
		wantErr string
	}{
		{name: "parse error", src: "package gen\nfunc {", wantErr: "parse:"},
		{name: "interface missing", src: "package gen\ntype X int\nfunc f() {}\n", wantErr: "type StrictServerInterface not found"},
		{name: "not an interface", src: "package gen\ntype StrictServerInterface struct{}\n", wantErr: "is not an interface"},
		{name: "embedded interface", src: "package gen\ntype StrictServerInterface interface{ Other }\ntype Other interface{}\n", wantErr: "embedded interfaces"},
		{name: "single result", src: header + "type StrictServerInterface interface{ Op(ctx context.Context) error }\n", wantErr: "must return (response, error)"},
		{name: "no result", src: header + "type StrictServerInterface interface{ Op(ctx context.Context) }\n", wantErr: "must return (response, error)"},
		{name: "second result not error", src: header + "type StrictServerInterface interface{ Op(ctx context.Context) (int, int) }\n", wantErr: "must return (response, error)"},
		{name: "unknown package in params", src: "package gen\ntype StrictServerInterface interface{ Op(x foo.Bar) (int, error) }\n", wantErr: `method Op: unknown package "foo"`},
		{name: "unknown package in results", src: "package gen\ntype StrictServerInterface interface{ Op() (foo.Bar, error) }\n", wantErr: `method Op: unknown package "foo"`},
		{name: "invalid package name", src: header + iface, wantErr: "format:"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			cfg := testCfg
			if tt.name == "invalid package name" {
				cfg.pkg = "not valid"
			}
			_, err := generate("gen.go", []byte(tt.src), cfg)
			if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
				t.Fatalf("error = %v, want containing %q", err, tt.wantErr)
			}
		})
	}
}

func TestImportSpec(t *testing.T) {
	tests := []struct{ name, path, want string }{
		{"context", "context", `"context"`},
		{"types", "github.com/x/types", `"github.com/x/types"`},
		{"openapi_types", "github.com/x/types", `openapi_types "github.com/x/types"`},
	}
	for _, tt := range tests {
		if got := importSpec(tt.name, tt.path); got != tt.want {
			t.Errorf("importSpec(%q, %q) = %q, want %q", tt.name, tt.path, got, tt.want)
		}
	}
}

func TestRun(t *testing.T) {
	fixture := filepath.Join("testdata", "gen.go")
	dir := t.TempDir()
	bad := filepath.Join(dir, "bad.go")
	if err := os.WriteFile(bad, []byte("package gen\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name       string
		args       []string
		wantCode   int
		wantOut    string
		wantErrOut string
		wantFile   string
	}{
		{name: "stdout", args: []string{"-in", fixture}, wantCode: 0, wantOut: "package stubs"},
		{name: "custom package", args: []string{"-in", fixture, "-pkg", "other"}, wantCode: 0, wantOut: "package other"},
		{name: "file output", args: []string{"-in", fixture, "-out", filepath.Join(dir, "out.go")}, wantCode: 0, wantFile: filepath.Join(dir, "out.go")},
		{name: "missing -in", args: nil, wantCode: 2, wantErrOut: "-in is required"},
		{name: "unknown flag", args: []string{"-nope"}, wantCode: 2, wantErrOut: "flag provided but not defined"},
		{name: "unreadable input", args: []string{"-in", filepath.Join(dir, "missing.go")}, wantCode: 1, wantErrOut: "genstubs:"},
		{name: "generation error", args: []string{"-in", bad}, wantCode: 1, wantErrOut: "StrictServerInterface not found"},
		{name: "unwritable output", args: []string{"-in", fixture, "-out", filepath.Join(dir, "no", "such", "out.go")}, wantCode: 1, wantErrOut: "genstubs:"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			if code := run(tt.args, &stdout, &stderr); code != tt.wantCode {
				t.Fatalf("exit code = %d, want %d (stderr: %s)", code, tt.wantCode, stderr.String())
			}
			if !strings.Contains(stdout.String(), tt.wantOut) {
				t.Errorf("stdout lacks %q", tt.wantOut)
			}
			if !strings.Contains(stderr.String(), tt.wantErrOut) {
				t.Errorf("stderr = %q, want containing %q", stderr.String(), tt.wantErrOut)
			}
			if tt.wantFile != "" {
				b, err := os.ReadFile(tt.wantFile)
				if err != nil || !bytes.HasPrefix(b, []byte("// Code generated by genstubs. DO NOT EDIT.")) {
					t.Errorf("output file not written correctly: %v", err)
				}
			}
		})
	}
}
