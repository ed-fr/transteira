package antivirus

// eicarKey is the XOR key of eicarObfuscated.
const eicarKey = 0xa5

// eicarObfuscated is the EICAR antivirus test string XORed with eicarKey, so
// that neither this source file nor the compiled binary contains the plain
// string (which local scanners would flag).
var eicarObfuscated = [...]byte{
	0xfd, 0x90, 0xea, 0x84, 0xf5, 0x80, 0xe5, 0xe4, 0xf5, 0xfe, 0x91, 0xf9,
	0xf5, 0xff, 0xfd, 0x90, 0x91, 0x8d, 0xf5, 0xfb, 0x8c, 0x92, 0xe6, 0xe6,
	0x8c, 0x92, 0xd8, 0x81, 0xe0, 0xec, 0xe6, 0xe4, 0xf7, 0x88, 0xf6, 0xf1,
	0xe4, 0xeb, 0xe1, 0xe4, 0xf7, 0xe1, 0x88, 0xe4, 0xeb, 0xf1, 0xec, 0xf3,
	0xec, 0xf7, 0xf0, 0xf6, 0x88, 0xf1, 0xe0, 0xf6, 0xf1, 0x88, 0xe3, 0xec,
	0xe9, 0xe0, 0x84, 0x81, 0xed, 0x8e, 0xed, 0x8f,
}

// EICAR returns a new copy of the 68-byte EICAR antivirus test string, the
// standard harmless content every antivirus engine reports as infected. It is
// used for the engine self-test (decision P44).
func EICAR() []byte {
	b := make([]byte, len(eicarObfuscated))
	for i, c := range eicarObfuscated {
		b[i] = c ^ eicarKey
	}
	return b
}
