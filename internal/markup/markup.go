// Package markup renders the limited Markdown of the legal documents of an
// entity (legal notice and privacy policy, CLAUDE.md section 13) to safe
// HTML.
//
// The supported syntax is deliberately small:
//
//   - paragraphs, separated by blank lines; every line break inside a
//     paragraph or a list item is kept as <br>;
//   - headings "# ", "## " and "### ", shifted down one level (h2 to h4)
//     because the page that shows the document already has its own h1;
//     "#### " and deeper are plain text;
//   - unordered lists ("- ", "* " or "+ ") and ordered lists ("1. " or
//     "1) "), one level; an indented line continues the previous item;
//   - **bold** or __bold__, *italic* or _italic_ (an underscore inside a
//     word, as in snake_case, is literal);
//   - links [text](url) and autolinks <url>, for https: and mailto: URLs
//     only: another URL leaves the text without link;
//   - backslash escapes of the punctuation above.
//
// There is no raw HTML: every "<", ">", "&" and quote of the source is
// escaped. The result is also passed through the allowlist of package
// sanitize, as a second line of defense. Rendering is linear in the size
// of the source.
package markup

import (
	"regexp"
	"strings"

	"github.com/ed-fr/transteira/internal/mail/sanitize"
)

// Limits of the inline scanner, which keep rendering linear.
const (
	maxLinkText   = 500
	maxURL        = 2048
	maxDelimDepth = 32
)

var (
	headingLine = regexp.MustCompile(`^(#{1,3})[ \t]+(.*?)[ \t]*#*[ \t]*$`)
	bulletLine  = regexp.MustCompile(`^[-*+][ \t]+(.*)$`)
	orderedLine = regexp.MustCompile(`^[0-9]{1,9}[.)][ \t]+(.*)$`)
)

// Markdown renders src to sanitized HTML.
func Markdown(src string) string {
	src = strings.ReplaceAll(strings.ReplaceAll(src, "\r\n", "\n"), "\r", "\n")
	r := &renderer{}
	for line := range strings.SplitSeq(src, "\n") {
		r.line(line)
	}
	r.closeBlock()
	return sanitize.HTML(strings.Join(r.out, "\n"))
}

// renderer accumulates the blocks of a document.
type renderer struct {
	out   []string
	para  []string // lines of the open paragraph
	list  string   // "ul" or "ol" when a list is open
	items [][]string
}

// line processes one source line.
func (r *renderer) line(line string) {
	if strings.TrimSpace(line) == "" {
		r.closeBlock()
		return
	}
	if m := headingLine.FindStringSubmatch(line); m != nil {
		r.closeBlock()
		tag := [...]string{"", "h2", "h3", "h4"}[len(m[1])]
		r.out = append(r.out, "<"+tag+">"+inline(m[2], true)+"</"+tag+">")
		return
	}
	if m := bulletLine.FindStringSubmatch(line); m != nil {
		r.item("ul", m[1])
		return
	}
	if m := orderedLine.FindStringSubmatch(line); m != nil {
		r.item("ol", m[1])
		return
	}
	if r.list != "" && (line[0] == ' ' || line[0] == '\t') {
		last := len(r.items) - 1
		r.items[last] = append(r.items[last], strings.TrimSpace(line))
		return
	}
	if r.list != "" {
		r.closeBlock()
	}
	r.para = append(r.para, strings.TrimSpace(line))
}

// item adds a list item, opening the list when needed.
func (r *renderer) item(kind, text string) {
	if r.list != kind {
		r.closeBlock()
		r.list = kind
	}
	r.items = append(r.items, []string{text})
}

// closeBlock writes the open paragraph or list.
func (r *renderer) closeBlock() {
	if len(r.para) > 0 {
		r.out = append(r.out, "<p>"+lines(r.para)+"</p>")
		r.para = nil
	}
	if r.list != "" {
		items := make([]string, len(r.items))
		for i, it := range r.items {
			items[i] = "<li>" + lines(it) + "</li>"
		}
		r.out = append(r.out, "<"+r.list+">\n"+strings.Join(items, "\n")+"\n</"+r.list+">")
		r.list, r.items = "", nil
	}
}

// lines renders lines of inline text separated by <br>.
func lines(ls []string) string {
	out := make([]string, len(ls))
	for i, l := range ls {
		out[i] = inline(l, true)
	}
	return strings.Join(out, "<br>\n")
}

// tokKind is the kind of an inline token.
type tokKind int

const (
	tokText  tokKind = iota // literal text, escaped on output
	tokHTML                 // HTML generated by this package
	tokDelim                // emphasis delimiter: "*", "_", "**" or "__"
)

// tok is an inline token.
type tok struct {
	kind tokKind
	s    string
	open bool // delimiter paired as an opener
	shut bool // delimiter paired as a closer
	// canOpen and canClose tell whether the delimiter is flanked to open
	// or close an emphasis.
	canOpen, canClose bool
}

// escaper escapes text for HTML content and attributes.
var escaper = strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&#34;", "'", "&#39;")

// inline renders the inline syntax of s; links are only recognized when
// links is set (not inside the text of a link).
func inline(s string, links bool) string {
	var toks []tok
	var text strings.Builder
	flush := func() {
		if text.Len() > 0 {
			toks = append(toks, tok{kind: tokText, s: text.String()})
			text.Reset()
		}
	}
	for i := 0; i < len(s); {
		c := s[i]
		switch {
		case c == '\\' && i+1 < len(s) && strings.IndexByte(`\*_[]()<>#-+.!`+"`", s[i+1]) >= 0:
			text.WriteByte(s[i+1])
			i += 2
			continue
		case c == '<' && links:
			if h, n := autolink(s[i:]); n > 0 {
				flush()
				toks = append(toks, tok{kind: tokHTML, s: h})
				i += n
				continue
			}
		case c == '[' && links:
			if h, n := link(s[i:]); n > 0 {
				flush()
				toks = append(toks, tok{kind: tokHTML, s: h})
				i += n
				continue
			}
		case c == '*' || c == '_':
			n := 1
			if i+1 < len(s) && s[i+1] == c {
				n = 2
			}
			// A run of three opens as "*" then "**" and closes as "**"
			// then "*", so that ***both*** nests properly.
			if n == 2 && i+2 < len(s) && s[i+2] == c && (i+3 >= len(s) || !isSpace(s[i+3])) && (i == 0 || isSpace(s[i-1])) {
				n = 1
			}
			flush()
			var before, after byte = ' ', ' '
			if i > 0 {
				before = s[i-1]
			}
			if i+n < len(s) {
				after = s[i+n]
			}
			t := tok{kind: tokDelim, s: s[i : i+n], canOpen: !isSpace(after), canClose: !isSpace(before)}
			if c == '_' {
				t.canOpen = t.canOpen && !isAlnum(before)
				t.canClose = t.canClose && !isAlnum(after)
			}
			toks = append(toks, t)
			i += n
			continue
		}
		text.WriteByte(c)
		i++
	}
	flush()
	pair(toks)
	var b strings.Builder
	for _, t := range toks {
		switch {
		case t.kind == tokHTML:
			b.WriteString(t.s)
		case t.kind == tokDelim && t.open:
			b.WriteString(map[bool]string{true: "<strong>", false: "<em>"}[len(t.s) == 2])
		case t.kind == tokDelim && t.shut:
			b.WriteString(map[bool]string{true: "</strong>", false: "</em>"}[len(t.s) == 2])
		default:
			b.WriteString(escaper.Replace(t.s))
		}
	}
	return b.String()
}

// pair matches emphasis delimiters: a closer pairs with the nearest
// identical opener among the last maxDelimDepth open ones; the openers left
// between them stay literal. Unpaired delimiters are literal text.
func pair(toks []tok) {
	var stack []int
	for i := range toks {
		t := &toks[i]
		if t.kind != tokDelim {
			continue
		}
		if t.canClose {
			found := -1
			for j := len(stack) - 1; j >= 0 && j >= len(stack)-maxDelimDepth; j-- {
				if toks[stack[j]].s == t.s {
					found = j
					break
				}
			}
			if found >= 0 {
				toks[stack[found]].open = true
				t.shut = true
				stack = stack[:found]
				continue
			}
		}
		if t.canOpen {
			stack = append(stack, i)
		}
	}
}

// autolink renders "<url>" at the start of s, returning the HTML and the
// bytes consumed, or 0.
func autolink(s string) (string, int) {
	end := strings.IndexByte(window(s, maxURL+2), '>')
	if end < 0 {
		return "", 0
	}
	u := s[1:end]
	if strings.ContainsAny(u, " \t<") {
		return "", 0
	}
	safe, ok := sanitize.SafeURL(u)
	if !ok {
		return "", 0
	}
	return `<a href="` + escaper.Replace(safe) + `">` + escaper.Replace(u) + "</a>", end + 1
}

// link renders "[text](url)" at the start of s, returning the HTML and the
// bytes consumed, or 0. A URL other than https: or mailto: renders the text
// without link.
func link(s string) (string, int) {
	closeText := strings.IndexByte(window(s, maxLinkText+2), ']')
	if closeText < 0 || closeText+1 >= len(s) || s[closeText+1] != '(' {
		return "", 0
	}
	rest := s[closeText+2:]
	closeURL := strings.IndexByte(window(rest, maxURL+1), ')')
	if closeURL < 0 {
		return "", 0
	}
	label := inline(s[1:closeText], false)
	n := closeText + 2 + closeURL + 1
	raw := strings.TrimSpace(rest[:closeURL])
	u, ok := sanitize.SafeURL(raw)
	if !ok || strings.ContainsAny(raw, " \t") {
		return label, n
	}
	return `<a href="` + escaper.Replace(u) + `">` + label + "</a>", n
}

// window returns the first n bytes of s at most, which bounds the searches
// of the inline scanner.
func window(s string, n int) string { return s[:min(n, len(s))] }

func isSpace(c byte) bool { return c == ' ' || c == '\t' || c == '\n' }

func isAlnum(c byte) bool {
	return c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= 0x80
}
