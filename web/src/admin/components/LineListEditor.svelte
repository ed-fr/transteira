<script lang="ts" generics="E extends string">
  // Text area of a list with one entry per line (CIDR ranges, domains), parsed live by
  // parseLineList (forms/lines.ts) with the parse function of the list. Shown under the field
  // and linked to it by aria-describedby: the number of entries (and the maximum), one error per
  // invalid line ("Line N: …") with a button applying the suggested value when there is one,
  // the duplicate lines (ignored) and the too-many notice. The form parses the same text with
  // the same function (parseLineList is pure) to build its body and refuse to save while there
  // are errors: the editor exposes no parsed list, which would need an effect writing a bound
  // prop on every render.
  //
  //   <LineListEditor label={text} hint={text} bind:value={cidrText}
  //                   parse={parseCidr} message={(e) => text(cidrLineMessage(e))} />
  import { tick } from 'svelte';
  import LiveRegion from '../../shared/components/LiveRegion.svelte';
  import { describedBy } from '../../shared/components/helpers';
  import { t } from '../../shared/i18n/i18n.svelte';
  import { parseLineList, type LineError, type ParseResult } from '../forms/lines';
  import { formatLineNumbers, replaceLine } from './fields';

  interface Props {
    /** Visible label. */
    label: string;
    /** Bound text of the text area. */
    value?: string;
    /** Parses one trimmed, non-blank line. */
    parse: (raw: string) => ParseResult<E>;
    /** Translated message of a line error (without the "Line N:" prefix). */
    message: (error: LineError<E>) => string;
    /** Maximum number of entries. */
    max?: number;
    /** Help text linked to the field. */
    hint?: string;
    /** Error of the whole field (e.g. from the server). */
    error?: string | undefined;
    /** Required field. */
    required?: boolean;
    /** Visible rows. */
    rows?: number;
    /** Element id of the text area (generated by default). */
    id?: string;
    /** The text area, for focus management. */
    element?: HTMLTextAreaElement | undefined;
  }

  let {
    label,
    value = $bindable(''),
    parse,
    message,
    max,
    hint,
    error,
    required = false,
    rows = 6,
    id,
    element = $bindable(),
  }: Props = $props();

  const uid = $props.id();
  const fieldId = $derived(id ?? `${uid}-lines`);
  const hintId = $derived(`${fieldId}-hint`);
  const countId = $derived(`${fieldId}-count`);
  const errorsId = $derived(`${fieldId}-line-errors`);
  const noticesId = $derived(`${fieldId}-notices`);
  const errorId = $derived(`${fieldId}-error`);

  const parsed = $derived(parseLineList(value, parse, max));
  const fieldInvalid = $derived(error !== undefined && error !== '');
  const linesInvalid = $derived(parsed.errors.length > 0 || parsed.tooMany);
  const hasNotices = $derived(parsed.duplicates.length > 0 || parsed.tooMany);
  let announcement = $state('');

  const count = $derived(
    max === undefined
      ? t('adminComponents.lineList.count', { count: parsed.values.length })
      : t('adminComponents.lineList.countMax', { count: parsed.values.length, max }),
  );

  async function applySuggestion(line: number, suggestion: string): Promise<void> {
    value = replaceLine(value, line, suggestion);
    announcement = t('adminComponents.lineList.replaced', { line, value: suggestion });
    await tick();
    element?.focus();
  }
</script>

<div class="tt-lines" class:tt-lines--invalid={fieldInvalid || linesInvalid}>
  <label class="tt-lines__label" for={fieldId}>
    {label}
    {#if required}<span class="tt-lines__required">{t('components.field.required')}</span>{/if}
  </label>
  {#if hint}
    <p class="tt-lines__hint" id={hintId}>{hint}</p>
  {/if}
  <textarea
    bind:this={element}
    bind:value
    id={fieldId}
    class="tt-lines__input"
    {rows}
    {required}
    autocomplete="off"
    autocapitalize="off"
    spellcheck="false"
    aria-invalid={fieldInvalid || linesInvalid ? 'true' : undefined}
    aria-describedby={describedBy(
      hint && hintId,
      countId,
      parsed.errors.length > 0 && errorsId,
      hasNotices && noticesId,
      fieldInvalid && errorId,
    )}></textarea>
  <p class="tt-lines__count" id={countId}>{count}</p>
  {#if parsed.errors.length > 0}
    <div class="tt-lines__errors" id={errorsId}>
      <p class="tt-lines__errors-title">
        <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
        {t('adminComponents.lineList.errorsTitle', { count: parsed.errors.length })}
      </p>
      <ul>
        {#each parsed.errors as lineError (lineError.line)}
          <li>
            {t('adminComponents.lineList.lineError', { line: lineError.line, message: message(lineError) })}
            {#if lineError.suggestion !== undefined}
              {@const suggestion = lineError.suggestion}
              <button
                type="button"
                class="tt-lines__suggest"
                onclick={() => applySuggestion(lineError.line, suggestion)}
              >
                {t('adminComponents.lineList.applySuggestion', { line: lineError.line, value: suggestion })}
              </button>
            {/if}
          </li>
        {/each}
      </ul>
    </div>
  {/if}
  {#if hasNotices}
    <div class="tt-lines__notices" id={noticesId}>
      {#if parsed.duplicates.length > 0}
        <p>
          {t('adminComponents.lineList.duplicates', {
            count: parsed.duplicates.length,
            lines: formatLineNumbers(parsed.duplicates),
          })}
        </p>
      {/if}
      {#if parsed.tooMany && max !== undefined}
        <p class="tt-lines__too-many">{t('adminComponents.lineList.tooMany', { max })}</p>
      {/if}
    </div>
  {/if}
  {#if fieldInvalid}
    <p class="tt-lines__error" id={errorId}>
      <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
      {error}
    </p>
  {/if}
  <LiveRegion message={announcement} />
</div>

