<script lang="ts">
  // Size field: an amount (decimal, dot or comma) and a binary unit (MiB, GiB, TiB), converted
  // to an exact number of bytes by forms/bytes.ts. The bound bytes is null while the field is
  // empty or invalid. The ceiling max (e.g. MAX_TRANSFER_BYTES, 20 GiB) is stated in the hint
  // and enforced; the client error is shown once the field was edited, and the error prop (from
  // the server) takes precedence.
  //
  //   <ByteSizeField label={text} bind:bytes={form.maxTransferBytes} max={MAX_TRANSFER_BYTES} required />
  import { untrack } from 'svelte';
  import TextField from '../../shared/components/TextField.svelte';
  import { locale, t } from '../../shared/i18n/i18n.svelte';
  import { BYTE_UNITS, type ByteUnit, formatBytes as formatBinaryBytes } from '../forms/bytes';
  import { byteErrorKey, byteFieldValue, validateByteField } from './fields';

  // Sizes are shown with the binary units of the size fields (MiB, GiB, TiB).
  const formatBytes = (n: number): string => formatBinaryBytes(n, locale.current);

  interface Props {
    /** Visible label of the amount. */
    label: string;
    /** Bound size in bytes; null when the field is empty or invalid. */
    bytes?: number | null;
    /** Ceiling in bytes (inclusive). */
    max?: number;
    /** Help text, before the ceiling notice. */
    hint?: string;
    /** Required field. */
    required?: boolean;
    /** Error from the server; takes precedence over the client error. */
    error?: string | undefined;
    /** Element id of the amount input (generated by default). */
    id?: string;
    /** Unit proposed when bytes is empty (default GiB). */
    defaultUnit?: ByteUnit;
    /** Bound: true when the field holds a valid size (or is empty and optional). */
    valid?: boolean;
    /** The amount input, for focus management. */
    element?: HTMLInputElement | undefined;
  }

  let {
    label,
    bytes = $bindable(null),
    max,
    hint,
    required = false,
    error,
    id,
    defaultUnit = 'GiB',
    valid = $bindable(true),
    element = $bindable(),
  }: Props = $props();

  const uid = $props.id();
  const inputId = $derived(id ?? `${uid}-amount`);

  // Value the field was last filled from: while the amount and unit are left as filled, bytes
  // keeps its exact value (a size that is not a whole number of units is shown rounded).
  const initial = untrack(() => ({ ...byteFieldValue(bytes, defaultUnit), bytes }));
  let filled = $state.raw(initial);
  let amount = $state(initial.amount);
  let unit = $state<ByteUnit>(initial.unit);
  let touched = $state(false);
  // Last value written to bytes by this field, to tell an outside change (reset) apart.
  let emitted: number | null = initial.bytes;

  const fieldState = $derived.by(() => {
    const parsed = validateByteField(amount, unit, max, required);
    return parsed.bytes !== null && amount === filled.amount && unit === filled.unit && filled.bytes !== null
      ? { ...parsed, bytes: filled.bytes }
      : parsed;
  });

  const clientError = $derived(
    fieldState.error === undefined
      ? undefined
      : t(`adminComponents.byteSize.errors.${byteErrorKey(fieldState.error)}`, {
          max: max === undefined ? '' : formatBytes(max),
        }),
  );

  const fullHint = $derived(
    [hint, max === undefined ? undefined : t('adminComponents.byteSize.max', { max: formatBytes(max) })]
      .filter((s) => s !== undefined && s !== '')
      .join(' '),
  );

  // The field drives bytes and valid.
  $effect(() => {
    emitted = fieldState.bytes;
    bytes = fieldState.bytes;
    const ok = fieldState.error === undefined;
    if (valid !== ok) {
      valid = ok;
    }
  });

  // An outside change of bytes (e.g. the form is reset to the saved values) refills the field.
  $effect.pre(() => {
    const outside = bytes;
    if (outside !== emitted) {
      filled = { ...byteFieldValue(outside, defaultUnit), bytes: outside };
      amount = filled.amount;
      unit = filled.unit;
      touched = false;
      emitted = outside;
    }
  });
</script>

{#snippet unitSelect()}
  <select
    class="tt-bytes__unit"
    aria-label={t('adminComponents.byteSize.unit', { label })}
    bind:value={unit}
    onchange={() => {
      touched = true;
    }}
  >
    {#each BYTE_UNITS as u (u)}
      <option value={u}>{u}</option>
    {/each}
  </select>
{/snippet}

<TextField
  {label}
  id={inputId}
  bind:value={amount}
  bind:element
  hint={fullHint === '' ? undefined : fullHint}
  error={error !== undefined && error !== '' ? error : touched ? clientError : undefined}
  {required}
  inputmode="decimal"
  autocomplete="off"
  addon={unitSelect}
  oninput={() => {
    touched = true;
  }}
  onblur={() => {
    if (amount !== '') {
      touched = true;
    }
  }}
/>

