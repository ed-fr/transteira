<script lang="ts">
  // Field of a secret the API never returns (e.g. the SMTP password). When a secret is stored,
  // a radio group offers to keep, replace or remove it, and the new value field appears only
  // in the replace mode. Without a stored secret, an optional password field is shown: typing
  // a value means replace, leaving it empty means keep (send nothing). The effective mode and
  // value are bound and passed to onchange (PasswordMode of forms/smtp.ts).
  //
  //   <SecretModeField legend={t('adminTenants.smtp.password.mode')} secretSet={stored.passwordSet}
  //                    bind:mode={form.passwordMode} bind:value={form.password} error={pwError} />
  import RadioGroup from '../../shared/components/RadioGroup.svelte';
  import { t } from '../../shared/i18n/i18n.svelte';
  import type { PasswordMode } from '../forms/smtp';
  import { effectiveSecretMode, type PasswordAutocomplete } from './fields';
  import PasswordField from './PasswordField.svelte';

  interface Props {
    /** Legend of the mode group, and label of the field when no secret is stored. */
    legend: string;
    /** Whether a secret is stored. */
    secretSet: boolean;
    /** Bound effective mode. */
    mode?: PasswordMode;
    /** Bound new value (meaningful in the replace mode only). */
    value?: string;
    /** Label of the new value field in the replace mode (default "New value"). */
    newLabel?: string;
    /** Labels of the three modes (defaults: generic texts). */
    keepLabel?: string;
    replaceLabel?: string;
    removeLabel?: string;
    /** Notice shown when a secret is stored (default: "A value is saved…"). */
    setNotice?: string;
    /** Help text of the field. */
    hint?: string;
    /** Error, shown on the value field (or on the group when the field is hidden). */
    error?: string | undefined;
    /** autocomplete of the value field (default off: a secret of a third-party service). */
    autocomplete?: PasswordAutocomplete;
    /** Element id of the value field, e.g. for the error summary (generated by default). */
    id?: string;
    /** Called after the mode or the value changed, with the effective mode. */
    onchange?: (mode: PasswordMode, value: string) => void;
  }

  let {
    legend,
    secretSet,
    mode = $bindable('keep'),
    value = $bindable(''),
    newLabel,
    keepLabel,
    replaceLabel,
    removeLabel,
    setNotice,
    hint,
    error,
    autocomplete = 'off',
    id,
    onchange,
  }: Props = $props();

  const uid = $props.id();
  const fieldId = $derived(id ?? `${uid}-secret`);

  const options = $derived([
    { value: 'keep' as const, label: keepLabel ?? t('adminComponents.secret.keep') },
    { value: 'replace' as const, label: replaceLabel ?? t('adminComponents.secret.replace') },
    { value: 'remove' as const, label: removeLabel ?? t('adminComponents.secret.remove') },
  ]);

  function emit(): void {
    const effective = effectiveSecretMode(secretSet, mode, value);
    mode = effective;
    if (effective !== 'replace') {
      value = '';
    }
    onchange?.(effective, value);
  }

  // Without a stored secret, the mode follows the value.
  $effect(() => {
    if (!secretSet) {
      const effective = effectiveSecretMode(false, mode, value);
      if (effective !== mode) {
        mode = effective;
      }
    }
  });
</script>

{#if secretSet}
  <RadioGroup
    {legend}
    {options}
    bind:value={mode}
    hint={setNotice ?? t('adminComponents.secret.set')}
    error={mode === 'replace' ? undefined : error}
    onchange={emit}
  />
  {#if mode === 'replace'}
    <PasswordField
      id={fieldId}
      label={newLabel ?? t('adminComponents.secret.new')}
      bind:value
      {autocomplete}
      {hint}
      {error}
      required
      oninput={() => onchange?.(mode, value)}
    />
  {/if}
{:else}
  <PasswordField
    id={fieldId}
    label={legend}
    bind:value
    {autocomplete}
    hint={hint ?? t('adminComponents.secret.notSet')}
    {error}
    oninput={() => onchange?.(effectiveSecretMode(false, mode, value), value)}
  />
{/if}
