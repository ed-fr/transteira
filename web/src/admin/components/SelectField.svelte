<script lang="ts">
  // Labelled native <select> (RGAA 11.1, 11.10), on the model of TextField: visible label,
  // optional hint, error message linked by aria-describedby with aria-invalid, required state
  // shown in the label text. Options may be grouped (<optgroup>).
  //
  //   <SelectField label={statusLabel} bind:value={status}
  //                options={[{ value: '', label: allLabel }, { value: 'active', label: activeLabel }]} />
  import { t } from '../../shared/i18n/i18n.svelte';
  import { describedBy } from '../../shared/components/helpers';
  import { isSelectGroup, type SelectEntry } from './select';

  interface Props {
    /** Visible label. */
    label: string;
    /** Options, or groups of options ({ group, label, options }). */
    options: readonly SelectEntry[];
    /** Bound value (the value of the selected option). */
    value?: string;
    /** Element id (generated by default). */
    id?: string;
    /** Name of the field in its form. */
    name?: string;
    /** Help text shown under the label and linked to the select. */
    hint?: string;
    /** Error message; sets aria-invalid and is linked to the select. */
    error?: string | undefined;
    /** Required field: native required attribute and "(required)" in the label. */
    required?: boolean;
    /** Disabled field. */
    disabled?: boolean;
    /** Called after the user changed the value (the bound value is already updated). */
    onchange?: (value: string) => void;
    /** The select element, for focus management. */
    element?: HTMLSelectElement | undefined;
    class?: string;
  }

  let {
    label,
    options,
    value = $bindable(''),
    id,
    name,
    hint,
    error,
    required = false,
    disabled = false,
    onchange,
    element = $bindable(),
    class: className = '',
  }: Props = $props();

  const uid = $props.id();
  const selectId = $derived(id ?? `${uid}-select`);
  const hintId = $derived(`${selectId}-hint`);
  const errorId = $derived(`${selectId}-error`);
  const invalid = $derived(error !== undefined && error !== '');
</script>

<div class="tt-field {className}" class:tt-field--invalid={invalid}>
  <label class="tt-field__label" for={selectId}>
    {label}
    {#if required}<span class="tt-field__required">{t('components.field.required')}</span>{/if}
  </label>
  {#if hint}
    <p class="tt-field__hint" id={hintId}>{hint}</p>
  {/if}
  <select
    bind:this={element}
    bind:value
    id={selectId}
    {name}
    class="tt-field__select"
    {required}
    {disabled}
    aria-invalid={invalid ? 'true' : undefined}
    aria-describedby={describedBy(hint && hintId, invalid && errorId)}
    onchange={() => onchange?.(value)}
  >
    {#each options as entry, index (index)}
      {#if isSelectGroup(entry)}
        <optgroup label={entry.label}>
          {#each entry.options as option (option.value)}
            <option value={option.value} disabled={option.disabled}>{option.label}</option>
          {/each}
        </optgroup>
      {:else}
        <option value={entry.value} disabled={entry.disabled}>{entry.label}</option>
      {/if}
    {/each}
  </select>
  {#if invalid}
    <p class="tt-field__error" id={errorId}>
      <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
      {error}
    </p>
  {/if}
</div>

