<script lang="ts">
  // Password input on TextField, with a show/hide toggle button (aria-pressed, constant
  // accessible name "Show <label>" that contains its visible text) and the autocomplete value
  // matching its use: current-password (sign-in), new-password (definition), off (secrets
  // of third-party services, e.g. SMTP). With confirmLabel, a second field asks to type the
  // password again and shows a mismatch error (passwordConfirmError) once it is typed.
  //
  //   <PasswordField label={text} bind:value={password} autocomplete="current-password" required />
  //   <PasswordField label={text} bind:value={pw} bind:confirmValue={pw2} autocomplete="new-password"
  //                  confirmLabel={t('adminComponents.password.confirmLabel')} />
  import type { HTMLInputAttributes } from 'svelte/elements';
  import TextField from '../../shared/components/TextField.svelte';
  import { t } from '../../shared/i18n/i18n.svelte';
  import { passwordConfirmError, type PasswordAutocomplete } from './fields';

  interface Props extends Omit<
    HTMLInputAttributes,
    | 'type'
    | 'value'
    | 'style'
    | 'children'
    | 'id'
    | 'aria-describedby'
    | 'aria-invalid'
    | 'autocomplete'
    | 'class'
  > {
    /** Visible label. */
    label: string;
    /** Bound value. */
    value?: string;
    /** autocomplete attribute: current-password, new-password or off. */
    autocomplete: PasswordAutocomplete;
    /** Element id of the input (generated by default). */
    id?: string;
    /** Help text linked to the input. */
    hint?: string;
    /** Error message of the input. */
    error?: string | undefined;
    /** Required field. */
    required?: boolean;
    /** The input element, for focus management. */
    element?: HTMLInputElement | undefined;
    /** Label of the confirmation field; the field is shown only when set. */
    confirmLabel?: string;
    /** Bound value of the confirmation field. */
    confirmValue?: string;
    /** Element id of the confirmation input (generated by default). */
    confirmId?: string;
    /** Error of the confirmation field from the server; the mismatch error is computed. */
    confirmError?: string | undefined;
    /** Bound: true when the confirmation is shown and matches the password (or is not asked). */
    confirmed?: boolean;
    class?: string;
  }

  let {
    label,
    value = $bindable(''),
    autocomplete,
    id,
    hint,
    error,
    required = false,
    element = $bindable(),
    confirmLabel,
    confirmValue = $bindable(''),
    confirmId,
    confirmError,
    confirmed = $bindable(true),
    class: className = '',
    ...rest
  }: Props = $props();

  const uid = $props.id();
  let visible = $state(false);

  const mismatch = $derived(
    confirmLabel !== undefined && passwordConfirmError(value, confirmValue) === 'mismatch'
      ? t('adminComponents.password.mismatch')
      : undefined,
  );

  $effect(() => {
    const ok = confirmLabel === undefined || (confirmValue === value && value !== '');
    if (confirmed !== ok) {
      confirmed = ok;
    }
  });
</script>

{#snippet toggle()}
  <button
    type="button"
    class="tt-password__toggle"
    aria-pressed={visible ? 'true' : 'false'}
    aria-label={t('adminComponents.password.show', { label })}
    onclick={() => {
      visible = !visible;
    }}
  >
    <!-- Toggle button pattern: the text stays the same, aria-pressed carries the state. -->
    <span aria-hidden="true">{t('admin.common.show')}</span>
  </button>
{/snippet}

<div class="tt-password {className}">
  <TextField
    {...rest}
    {label}
    bind:value
    bind:element
    type={visible ? 'text' : 'password'}
    id={id ?? `${uid}-password`}
    {hint}
    {error}
    {required}
    {autocomplete}
    autocapitalize="off"
    spellcheck={false}
    addon={toggle}
  />
  {#if confirmLabel !== undefined}
    <TextField
      label={confirmLabel}
      bind:value={confirmValue}
      type={visible ? 'text' : 'password'}
      id={confirmId ?? `${uid}-confirm`}
      error={confirmError ?? mismatch}
      {required}
      {autocomplete}
      autocapitalize="off"
      spellcheck={false}
    />
  {/if}
</div>

<style>
  .tt-password__toggle {
    flex: none;
    min-width: 5rem;
    padding: 0 var(--tt-space-3);
    border: var(--tt-border-width) solid var(--tt-border);
    border-radius: var(--tt-radius);
    background: var(--tt-surface);
    color: var(--tt-text);
    cursor: pointer;
  }

  .tt-password__toggle[aria-pressed='true'] {
    background: var(--tt-surface-muted);
    border-width: 2px;
  }
</style>
