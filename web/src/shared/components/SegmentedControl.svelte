<script lang="ts" generics="T extends string | number">
  // Segmented control (CLAUDE.md section 13.2: durations, confidentiality levels): a <fieldset>
  // with its <legend> and native radio buttons drawn as joined segments, so that the arrow keys,
  // the form semantics and getByRole('radio', { name }) work natively. Each transparent radio
  // covers its segment (44 px high at least), so that a click on the segment hits the radio itself.
  // The chosen segment is marked by a 2 px border in --tt-graphic (3:1 on the --tt-surface of the
  // group) and a bold label, never by colour alone; the focused one by the focus ring. Segments
  // wrap to new lines when they do not fit (4 options or more on a phone).
  //
  // An option may have a description (e.g. the rules of a confidentiality level): every radio is
  // described by its own description (aria-describedby), and only the description of the chosen
  // option is shown under the group.
  //
  // Props:
  //   legend     visible legend of the group
  //   options    { value, label, description?, disabled?, lang? }[]
  //   value      bindable chosen value
  //   name       name of the radios (generated by default)
  //   hint       help text linked to the group
  //   error      error message linked to the group
  //   required   "(required)" in the legend and required radios
  //   disabled   disables the whole group
  //   onchange   called with the value after a user choice
  import { t } from '../i18n/i18n.svelte';
  import { describedBy } from './helpers';

  /** One choice of the group. */
  interface SegmentOption {
    value: T;
    label: string;
    /** Shown under the group when chosen, and describing its radio. */
    description?: string | undefined;
    disabled?: boolean | undefined;
    /** Language of the label when it differs from the page (e.g. a native language name). */
    lang?: string | undefined;
  }

  interface Props {
    /** Legend of the group (visible). */
    legend: string;
    /** Choices. */
    options: readonly SegmentOption[];
    /** Bound chosen value. */
    value?: T | undefined;
    /** Name of the radio buttons (generated by default). */
    name?: string;
    /** Help text linked to the group. */
    hint?: string | undefined;
    /** Error message; linked to the group. */
    error?: string | undefined;
    /** Required group. */
    required?: boolean;
    /** Disables the whole group. */
    disabled?: boolean;
    /** Called after the choice changed. */
    onchange?: (value: T) => void;
    class?: string;
  }

  let {
    legend,
    options,
    value = $bindable(),
    name,
    hint,
    error,
    required = false,
    disabled = false,
    onchange,
    class: className = '',
  }: Props = $props();

  const uid = $props.id();
  const groupName = $derived(name ?? `${uid}-segment`);
  const hintId = `${uid}-hint`;
  const errorId = `${uid}-error`;
  const invalid = $derived(error !== undefined && error !== '');
</script>

<fieldset
  class="tt-seg {className}"
  {disabled}
  aria-describedby={describedBy(hint && hintId, invalid && errorId)}
>
  <legend class="tt-seg__legend">
    {legend}
    {#if required}<span class="tt-seg__required">{t('components.field.required')}</span>{/if}
  </legend>
  {#if hint}
    <p class="tt-seg__hint" id={hintId}>{hint}</p>
  {/if}
  <div class="tt-seg__options" class:tt-seg__options--invalid={invalid}>
    {#each options as option, index (option.value)}
      <div class="tt-seg__option">
        <input
          type="radio"
          class="tt-seg__input"
          id="{uid}-{index}"
          name={groupName}
          value={option.value}
          checked={value === option.value}
          disabled={option.disabled}
          {required}
          aria-describedby={option.description ? `${uid}-${index}-desc` : undefined}
          onchange={() => {
            value = option.value;
            onchange?.(option.value);
          }}
        />
        <label class="tt-seg__label" for="{uid}-{index}" lang={option.lang}>{option.label}</label>
      </div>
    {/each}
  </div>
  {#each options as option, index (option.value)}
    {#if option.description}
      <p class="tt-seg__description" id="{uid}-{index}-desc" hidden={value !== option.value}>
        {option.description}
      </p>
    {/if}
  {/each}
  {#if invalid}
    <p class="tt-seg__error" id={errorId}>
      <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
      {error}
    </p>
  {/if}
</fieldset>

