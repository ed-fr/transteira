<script lang="ts">
  // File selection: a real <input type="file"> (the keyboard and screen reader path, focusable,
  // opened with Enter or Space) visually replaced by its label, which is also a drop zone for
  // mouse users. Dropped and chosen files both go to onfiles.
  import { t } from '../i18n/i18n.svelte';
  import { describedBy, dropTarget, filesOf } from './helpers';

  interface Props {
    /** Visible label of the field (e.g. "Files to send"). */
    label: string;
    /** Help text (limits, allowed size), linked to the input. */
    hint?: string;
    /** Error message; sets aria-invalid and is linked to the input. */
    error?: string | undefined;
    /** Allows several files (default true). */
    multiple?: boolean;
    /** Accepted types (accept attribute). */
    accept?: string;
    /** Disables selection and drops. */
    disabled?: boolean;
    /** Required field. */
    required?: boolean;
    /** Element id of the input (generated by default). */
    id?: string;
    /** Called with the chosen or dropped files (never empty). */
    onfiles: (files: File[]) => void;
    /** The input element, for focus management. */
    element?: HTMLInputElement | undefined;
    class?: string;
  }

  let {
    label,
    hint,
    error,
    multiple = true,
    accept,
    disabled = false,
    required = false,
    id,
    onfiles,
    element = $bindable(),
    class: className = '',
  }: Props = $props();

  const uid = $props.id();
  const inputId = $derived(id ?? `${uid}-files`);
  const hintId = $derived(`${inputId}-hint`);
  const errorId = $derived(`${inputId}-error`);
  const invalid = $derived(error !== undefined && error !== '');
  let active = $state(false);

  function handleChange(event: Event & { currentTarget: HTMLInputElement }): void {
    const input = event.currentTarget;
    const files = filesOf(input.files);
    // Reset, so that choosing the same file again (after removing it) fires change again.
    input.value = '';
    if (files.length > 0) {
      onfiles(files);
    }
  }

  const drop = dropTarget({
    onfiles: (files) => onfiles(multiple ? files : files.slice(0, 1)),
    onactive: (value) => {
      active = value;
    },
    disabled: () => disabled,
  });
</script>

<div
  class="tt-drop {className}"
  class:tt-drop--active={active}
  class:tt-drop--invalid={invalid}
  {@attach drop}
>
  <p class="tt-drop__title" id="{inputId}-title">{label}</p>
  {#if hint}
    <p class="tt-drop__hint" id={hintId}>{hint}</p>
  {/if}
  <input
    bind:this={element}
    type="file"
    id={inputId}
    class="tt-drop__input"
    {multiple}
    {accept}
    {disabled}
    {required}
    aria-labelledby="{inputId}-title {inputId}-label"
    aria-invalid={invalid ? 'true' : undefined}
    aria-describedby={describedBy(hint && hintId, invalid && errorId)}
    onchange={handleChange}
  />
  <label class="tt-drop__zone" for={inputId} id="{inputId}-label">
    {#if active}
      {t('components.fileDrop.active')}
    {:else}
      {t('components.fileDrop.instructions')}
      <span class="tt-drop__browse">{t('components.fileDrop.browse')}</span>
    {/if}
  </label>
  {#if invalid}
    <p class="tt-drop__error" id={errorId}>
      <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
      {error}
    </p>
  {/if}
</div>

