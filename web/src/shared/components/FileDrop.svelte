<script lang="ts">
  // File selection: a real <input type="file"> (the keyboard and screen reader path, focusable,
  // opened with Enter or Space) visually replaced by its label, which is also a drop zone for
  // mouse users. Dropped and chosen files both go to onfiles.
  //
  // Variants:
  //   'default'  the label is a dashed zone "Drag and drop files here, or choose files" under the
  //              visible title (label prop) and the hint; "Add a folder" button in folders mode
  //   'hero'     large dashed zone of the public deposit (CLAUDE.md section 13.2): a round upload
  //              icon, a title ("Drag and drop your files here", "…files or folders here" in
  //              folders mode), the hint, then two buttons: "Choose files" (the label of the input,
  //              drawn as a primary button: the input keeps the focus, its focus ring is drawn on
  //              it, and it opens with Enter or Space) and "Choose a folder" (a real button, in
  //              folders mode when the browser can pick a folder). The label prop stays the start
  //              of the accessible name of the input ("Files to send Choose files", visually
  //              hidden), so getByLabel(/^Files to send/) and setInputFiles keep working. The whole
  //              zone accepts drops.
  import { t } from '../i18n/i18n.svelte';
  import Icon from './Icon.svelte';
  import { describedBy, dropTarget, filesOf } from './helpers';
  import {
    pickedFromInput,
    summarizePick,
    supportsFolderPicker,
    type AcceptedFile,
    type PickedFile,
    type PickNotice,
  } from './folders';

  interface Props {
    /** Visible label of the field (e.g. "Files to send"). */
    label: string;
    /** Help text (limits, allowed size), linked to the input. */
    hint?: string;
    /** Error message; sets aria-invalid and is linked to the input. */
    error?: string | undefined;
    /** Allows several files (default true). */
    multiple?: boolean;
    /** Accepted types (accept attribute). */
    accept?: string;
    /** Disables selection and drops. */
    disabled?: boolean;
    /** Required field. */
    required?: boolean;
    /** Element id of the input (generated by default). */
    id?: string;
    /** Called with the chosen or dropped files (never empty). */
    onfiles: (files: File[]) => void;
    /**
     * Accepts folders (drag and drop, and the "Add a folder" button). Picked files then go to
     * onpicked, with their relative folder, instead of onfiles.
     */
    folders?: boolean;
    /** Called with the picked files kept after filtering (folders mode; never empty). */
    onpicked?: (files: AcceptedFile[]) => void;
    /** Number of files that can still be added (folders mode; 1000 by default). */
    room?: number;
    /** Whether the browser can pick a folder (feature detection; injectable for tests). */
    folderPicker?: boolean;
    /** The input element, for focus management. */
    element?: HTMLInputElement | undefined;
    /** Look of the zone: default (form field) or hero (large public deposit zone). */
    variant?: 'default' | 'hero';
    /** Title of the hero zone, instead of the default "Drag and drop your files (or folders) here". */
    heroTitle?: string | undefined;
    class?: string;
  }

  let {
    label,
    hint,
    error,
    multiple = true,
    accept,
    disabled = false,
    required = false,
    id,
    onfiles,
    folders = false,
    onpicked,
    room,
    folderPicker = supportsFolderPicker(),
    element = $bindable(),
    variant = 'default',
    heroTitle,
    class: className = '',
  }: Props = $props();

  const uid = $props.id();
  const inputId = $derived(id ?? `${uid}-files`);
  const hintId = $derived(`${inputId}-hint`);
  const errorId = $derived(`${inputId}-error`);
  const invalid = $derived(error !== undefined && error !== '');
  const foldersOn = $derived(folders && onpicked !== undefined);
  const hero = $derived(variant === 'hero');
  const heroText = $derived(
    heroTitle ?? t(foldersOn ? 'components.fileDrop.heroTitleFolders' : 'components.fileDrop.heroTitle'),
  );
  let active = $state(false);
  let folderInput: HTMLInputElement | undefined = $state();
  let notice: PickNotice | undefined = $state();

  /** Filters what was picked, reports what was left out, and hands the rest over. */
  function deliver(picked: readonly PickedFile[]): void {
    const result = summarizePick(picked, room);
    notice = result.notice;
    if (result.accepted.length > 0) {
      onpicked?.(result.accepted);
    }
  }

  function handleChange(event: Event & { currentTarget: HTMLInputElement }): void {
    const input = event.currentTarget;
    const files = filesOf(input.files);
    // Reset, so that choosing the same file again (after removing it) fires change again.
    input.value = '';
    if (files.length === 0) {
      return;
    }
    if (foldersOn) {
      deliver(files.map((file) => ({ file, path: '' })));
    } else {
      onfiles(files);
    }
  }

  function handleFolder(event: Event & { currentTarget: HTMLInputElement }): void {
    const input = event.currentTarget;
    const picked = pickedFromInput(input.files);
    input.value = '';
    deliver(picked);
  }

  const drop = dropTarget({
    onfiles: (files) => onfiles(multiple ? files : files.slice(0, 1)),
    onpicked: (promise) => void promise.then(deliver),
    folders: () => foldersOn,
    onactive: (value) => {
      active = value;
    },
    disabled: () => disabled,
  });
</script>

<div
  class="tt-drop {className}"
  class:tt-drop--hero={hero}
  class:tt-drop--active={active}
  class:tt-drop--invalid={invalid}
  {@attach drop}
>
  {#snippet input()}
    <input
      bind:this={element}
      type="file"
      id={inputId}
      class="tt-drop__input"
      {multiple}
      {accept}
      {disabled}
      {required}
      aria-labelledby="{inputId}-title {inputId}-label"
      aria-invalid={invalid ? 'true' : undefined}
      aria-describedby={describedBy(hint && hintId, invalid && errorId)}
      onchange={handleChange}
    />
  {/snippet}
  {#snippet folderPick(buttonClass: string, text: string)}
    {#if foldersOn && folderPicker}
      <input
        bind:this={folderInput}
        type="file"
        class="tt-drop__folder-input"
        tabindex="-1"
        aria-hidden="true"
        multiple
        webkitdirectory
        {disabled}
        onchange={handleFolder}
      />
      <button type="button" class={buttonClass} {disabled} onclick={() => folderInput?.click()}>
        {#if hero}<Icon name="folder" />{/if}
        {text}
      </button>
    {/if}
  {/snippet}
  {#if hero}
    <p class="visually-hidden" id="{inputId}-title">{label}</p>
    <div class="tt-drop__hero">
      <span class="tt-drop__disc" aria-hidden="true"><Icon name="upload" size="xl" /></span>
      <p class="tt-drop__hero-title">
        {active ? t('components.fileDrop.active') : heroText}
      </p>
      {#if hint}
        <p class="tt-drop__hint" id={hintId}>{hint}</p>
      {/if}
      <div class="tt-drop__actions">
        {@render input()}
        <label class="tt-drop__choose" for={inputId} id="{inputId}-label">
          <Icon name="upload" />
          {t('components.fileDrop.chooseFiles')}
        </label>
        {@render folderPick(
          'tt-drop__choose tt-drop__choose--secondary',
          t('components.fileDrop.chooseFolder'),
        )}
      </div>
    </div>
  {:else}
    <p class="tt-drop__title" id="{inputId}-title">{label}</p>
    {#if hint}
      <p class="tt-drop__hint" id={hintId}>{hint}</p>
    {/if}
    {@render input()}
    <label class="tt-drop__zone" for={inputId} id="{inputId}-label">
      {#if active}
        {t('components.fileDrop.active')}
      {:else}
        {t('components.fileDrop.instructions')}
        <span class="tt-drop__browse">{t('components.fileDrop.browse')}</span>
      {/if}
    </label>
    {@render folderPick('tt-drop__folder-button', t('components.fileDrop.addFolder'))}
  {/if}
  <div class="tt-drop__notice" role="status">
    {#if notice}
      {#if notice.empty}
        <p>{t('components.fileDrop.emptyFolder')}</p>
      {/if}
      {#if notice.excluded > 0}
        <p>{t('components.fileDrop.excluded', { count: notice.excluded })}</p>
      {/if}
      {#if notice.rejected.length > 0}
        <p>{t('components.fileDrop.rejected', { count: notice.rejected.length })}</p>
        <ul>
          {#each notice.rejected.slice(0, 5) as item, i (i)}
            <li class="tt-break">
              {t('components.fileDrop.rejectedItem', {
                name: item.display,
                reason: t(`components.fileDrop.reason.${item.reason}`),
              })}
            </li>
          {/each}
        </ul>
        {#if notice.rejected.length > 5}
          <p>{t('components.fileDrop.rejectedMore', { count: notice.rejected.length - 5 })}</p>
        {/if}
      {/if}
    {/if}
  </div>
  {#if invalid}
    <p class="tt-drop__error" id={errorId}>
      <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
      {error}
    </p>
  {/if}
</div>

