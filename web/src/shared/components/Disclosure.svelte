<script lang="ts">
  // Disclosure block (CLAUDE.md section 13.2, "Security options" of the deposit): a real <button>
  // with aria-expanded and aria-controls, followed by its panel (hidden attribute when closed). The
  // button shows the summary, an optional count badge ("1 active", part of the accessible name) and
  // a chevron turned by the state. Open it programmatically through the bindable open (e.g. when an
  // option inside is in error, before focusing it).
  //
  // Props:
  //   summary       text of the button
  //   count         optional count text after the summary ("1 active"); hidden when empty
  //   open          bindable state (closed by default)
  //   headingLevel  wraps the button in a heading of that level (2 to 4), as an accordion header
  //   ontoggle      called with the new state after a click
  //   id            id of the panel (generated by default)
  //   children      content of the panel
  import type { Snippet } from 'svelte';
  import Icon from './Icon.svelte';

  interface Props {
    /** Text of the button. */
    summary: string;
    /** Count text after the summary (e.g. "1 active"). */
    count?: string | undefined;
    /** Bound open state. */
    open?: boolean;
    /** Heading level wrapping the button. */
    headingLevel?: 2 | 3 | 4 | undefined;
    /** Called with the new state after a click. */
    ontoggle?: (open: boolean) => void;
    /** Id of the panel. */
    id?: string;
    /** The button element, for focus management. */
    element?: HTMLButtonElement | undefined;
    /** Content of the panel. */
    children: Snippet;
    class?: string;
  }

  let {
    summary,
    count,
    open = $bindable(false),
    headingLevel,
    ontoggle,
    id,
    element = $bindable(),
    children,
    class: className = '',
  }: Props = $props();

  const uid = $props.id();
  const panelId = $derived(id ?? `${uid}-panel`);
  const headingTag = $derived(`h${headingLevel ?? 2}`);

  function toggle(): void {
    open = !open;
    ontoggle?.(open);
  }
</script>

{#snippet button()}
  <button
    bind:this={element}
    type="button"
    class="tt-disclosure__button"
    aria-expanded={open ? 'true' : 'false'}
    aria-controls={panelId}
    onclick={toggle}
  >
    <span class="tt-disclosure__summary">{summary}</span>
    {#if count}<span class="tt-disclosure__count">{count}</span>{/if}
    <span class="tt-disclosure__chevron"><Icon name="chevron" /></span>
  </button>
{/snippet}

<div class="tt-disclosure {className}" class:tt-disclosure--open={open}>
  {#if headingLevel}
    <svelte:element this={headingTag} class="tt-disclosure__heading">{@render button()}</svelte:element>
  {:else}
    {@render button()}
  {/if}
  <div class="tt-disclosure__panel" id={panelId} hidden={!open}>
    {@render children()}
  </div>
</div>

