<script lang="ts">
  // On / off switch (CLAUDE.md section 13.2): a native <input type="checkbox" role="switch">, so
  // that the keyboard (Space), the form semantics and Playwright's check() all work natively, and
  // screen readers announce "switch, on / off". The visible label is a real <label for>; the
  // optional hint, lock reason and error are linked with aria-describedby (error: aria-invalid).
  //
  // Look: a track and a thumb drawn next to the label. The transparent input covers the track and
  // its 44 px target area, so that a click on the track hits the input itself. Off: track on
  // --tt-surface with a --tt-border outline, thumb in --tt-muted. On: track in --tt-graphic (3:1
  // on --tt-surface, checked in theme.ts and tokens.test.ts), thumb in --tt-surface, so that the
  // on state also reaches 3:1 against the thumb. The state is never conveyed by colour alone: the
  // thumb moves to the end of the track and shows a check mark when on. Forced colours: system
  // colours (Highlight / CanvasText) keep the track, thumb and check mark visible.
  //
  // Props:
  //   label     visible label (accessible name of the switch)
  //   checked   bindable state
  //   id        element id of the input (generated by default)
  //   hint      help text under the label
  //   locked    reason why the state cannot be changed (e.g. imposed by a confidentiality level):
  //             the switch is disabled and shows a lock icon with this text
  //   disabled  native disabled state (without a reason)
  //   error     error message (aria-invalid)
  //   onchange  called with the new state after a user change
  //   element   bindable input element (focus management)
  // Any other input attribute (name, aria-controls...) is passed to the input.
  import type { HTMLInputAttributes } from 'svelte/elements';
  import { t } from '../i18n/i18n.svelte';
  import { describedBy } from './helpers';
  import Icon from './Icon.svelte';

  interface Props extends Omit<
    HTMLInputAttributes,
    | 'type'
    | 'role'
    | 'checked'
    | 'style'
    | 'children'
    | 'id'
    | 'aria-describedby'
    | 'aria-invalid'
    | 'disabled'
    | 'onchange'
  > {
    /** Visible label. */
    label: string;
    /** Bound state. */
    checked?: boolean;
    /** Element id of the input (generated by default). */
    id?: string;
    /** Help text linked to the switch. */
    hint?: string | undefined;
    /** Reason why the switch is locked in its state: disabled, lock icon and this text. */
    locked?: string | undefined;
    /** Native disabled state. */
    disabled?: boolean;
    /** Error message; sets aria-invalid. */
    error?: string | undefined;
    /** Called with the new state after a user change. */
    onchange?: (checked: boolean) => void;
    /** The input element, for focus management. */
    element?: HTMLInputElement | undefined;
  }

  let {
    label,
    checked = $bindable(false),
    id,
    hint,
    locked,
    disabled = false,
    error,
    onchange,
    element = $bindable(),
    class: className = '',
    ...rest
  }: Props = $props();

  const uid = $props.id();
  const inputId = $derived(id ?? `${uid}-switch`);
  const hintId = $derived(`${inputId}-hint`);
  const lockedId = $derived(`${inputId}-locked`);
  const errorId = $derived(`${inputId}-error`);
  const isLocked = $derived(locked !== undefined && locked !== '');
  const invalid = $derived(error !== undefined && error !== '');
</script>

<div
  class="tt-switch {className}"
  class:tt-switch--locked={isLocked}
  class:tt-switch--disabled={disabled && !isLocked}
>
  <div class="tt-switch__row">
    <label class="tt-switch__label" for={inputId}>{label}</label>
    <span class="tt-switch__control">
      <input
        {...rest}
        bind:this={element}
        bind:checked
        type="checkbox"
        role="switch"
        id={inputId}
        class="tt-switch__input"
        disabled={disabled || isLocked}
        aria-invalid={invalid ? 'true' : undefined}
        aria-describedby={describedBy(hint && hintId, isLocked && lockedId, invalid && errorId)}
        onchange={(event) => onchange?.(event.currentTarget.checked)}
      />
      <span class="tt-switch__track" aria-hidden="true">
        <span class="tt-switch__thumb"><Icon name="check" size="xs" /></span>
      </span>
    </span>
  </div>
  {#if hint}
    <p class="tt-switch__hint" id={hintId}>{hint}</p>
  {/if}
  {#if isLocked}
    <p class="tt-switch__hint tt-switch__locked" id={lockedId}>
      <Icon name="lock" size="sm" />
      <span>{locked}</span>
    </p>
  {/if}
  {#if invalid}
    <p class="tt-switch__error" id={errorId}>
      <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
      {error}
    </p>
  {/if}
</div>

