<script lang="ts">
  // Recipient input (CLAUDE.md section 13.2): the addresses already entered are chips, followed by a
  // text input for the next one. The input is a real <input> with a visible <label> ("Recipients
  // (required)"), so getByRole('textbox', { name: /^Recipients/ }) keeps working.
  //
  // An address becomes a chip (oncommit) on Enter, on a comma or a semicolon, on a paste (the whole
  // pasted text, split by parseRecipients: several lines, "Name <address>"), and when the input
  // loses the focus. Enter with an empty input submits the form as usual. Addresses already in the
  // list are ignored with a visible notice. Every change is announced (announce()).
  //
  // The commit on blur must not move the controls under the pointer: a press on Send or "Security
  // options" blurs the input before its click, so the commit waits until that press is over
  // (PointerPress), and is skipped if the focus came back to the input meanwhile. The layout also
  // stays put for a first chip: a row of chips is as high as the input, and the input keeps to the
  // end of the last row of chips while 6rem are left there.
  //
  // The input collects third-party addresses: autocomplete="off" (the token "email" would mean the
  // depositor's own address, WCAG 1.3.5), with the email keyboard (inputmode).
  //
  // A chip shows the address and a remove button ("Remove <address>", a 44 px target). An invalid
  // chip (not an email address, or refused by the server: issues) is drawn in the danger colours
  // with an alert icon and a visually hidden "not accepted"; its reason is listed under the field
  // ("<address>: <reason>"), in the error linked to the input. Backspace in an empty input moves
  // the focus to the last chip; Backspace or Delete on a chip removes it, and the focus goes back to
  // the input.
  //
  // Props:
  //   label       visible label of the input
  //   recipients  committed addresses (the chips)
  //   draft       bindable text of the input (the address being typed)
  //   id          element id of the input (generated by default)
  //   hint        help text linked to the input
  //   required    "(required)" in the label; aria-required while there is no chip
  //   disabled    disables the input and the remove buttons
  //   error       general error of the field (e.g. required, too many)
  //   issues      reasons of refused addresses, by index in recipients (e.g. from the server)
  //   oncommit    commits the draft to the list; returns what was added and left out
  //   onremove    removes the chip at index
  //   element     bindable input element (focus management)
  import { onMount, tick } from 'svelte';
  import { t } from '../i18n/i18n.svelte';
  import { isEmail } from '../validation/email';
  import { announce } from './announce.svelte';
  import { describedBy } from './helpers';
  import Icon from './Icon.svelte';
  import { PointerPress } from './pointerPress';
  import {
    commitFeedback,
    commitsLeftDraft,
    pastedValue,
    recipientKeyAction,
    removesChip,
    RECIPIENT_SEPARATORS,
    splitDraft,
    type RecipientCommit,
  } from './recipients';

  interface Props {
    /** Visible label of the input. */
    label: string;
    /** Committed addresses (chips). */
    recipients: readonly string[];
    /** Text of the input (bindable). */
    draft?: string;
    /** Element id of the input (generated by default). */
    id?: string;
    /** Help text linked to the input. */
    hint?: string | undefined;
    /** Required field: "(required)" in the label. */
    required?: boolean;
    /** Disables the input and the remove buttons. */
    disabled?: boolean;
    /** General error of the field. */
    error?: string | undefined;
    /** Reasons of refused addresses, by index in recipients. */
    issues?: ReadonlyMap<number, string> | undefined;
    /** Commits the draft; returns the added addresses and those already in the list. */
    oncommit: () => RecipientCommit;
    /** Removes the chip at index. */
    onremove: (index: number) => void;
    /** The input element, for focus management. */
    element?: HTMLInputElement | undefined;
    class?: string;
  }

  let {
    label,
    recipients,
    draft = $bindable(''),
    id,
    hint,
    required = false,
    disabled = false,
    error,
    issues,
    oncommit,
    onremove,
    element = $bindable(),
    class: className = '',
  }: Props = $props();

  const uid = $props.id();
  const inputId = $derived(id ?? `${uid}-recipients`);
  const hintId = $derived(`${inputId}-hint`);
  const noticeId = $derived(`${inputId}-notice`);
  const errorId = $derived(`${inputId}-error`);
  let removeButtons: (HTMLButtonElement | null)[] = $state([]);
  /** Addresses left out by the last commit (already in the list). */
  let notice: string | undefined = $state();

  /** Reason of each refused chip: given by the parent, else "not an email address". */
  const chipIssues = $derived(
    recipients.map(
      (address, index) =>
        issues?.get(index) ?? (isEmail(address) ? undefined : t('fieldErrors.invalid-email')),
    ),
  );
  const refused = $derived(
    recipients.flatMap((address, index) => {
      const reason = chipIssues[index];
      return reason === undefined ? [] : [{ address, reason }];
    }),
  );
  const hasError = $derived((error !== undefined && error !== '') || refused.length > 0);

  /** Commits the draft and announces what changed. */
  function commit(): void {
    const feedback = commitFeedback(oncommit(), isEmail);
    notice = feedback.notice === undefined ? undefined : t(feedback.notice.key, feedback.notice.params);
    if (feedback.announcements.length > 0) {
      announce(feedback.announcements.map((m) => t(m.key, m.params)).join(' '));
    }
  }

  function handleInput(event: Event & { currentTarget: HTMLInputElement }): void {
    const input = event.currentTarget;
    const value = input.value;
    if (!RECIPIENT_SEPARATORS.test(value)) {
      draft = value;
      return;
    }
    // A separator was typed (or the value was set at once): the addresses before it are complete.
    const { complete, rest } = splitDraft(value);
    draft = complete;
    commit();
    draft = rest;
    input.value = rest;
  }

  function handlePaste(event: ClipboardEvent & { currentTarget: HTMLInputElement }): void {
    const text = event.clipboardData?.getData('text') ?? '';
    if (text === '') {
      return;
    }
    // The input would drop the line breaks of a pasted list: the whole text is committed at once.
    event.preventDefault();
    const input = event.currentTarget;
    draft = pastedValue(input.value, input.selectionStart, input.selectionEnd, text);
    commit();
    input.value = draft;
  }

  function handleKeydown(event: KeyboardEvent): void {
    const action = recipientKeyAction(event.key, draft, recipients.length);
    if (action === 'commit') {
      // Enter adds the address instead of submitting the form.
      event.preventDefault();
      commit();
    } else if (action === 'focus-last') {
      event.preventDefault();
      removeButtons[recipients.length - 1]?.focus();
    }
  }

  // Presses of the pointer on the page, to defer the commit on blur (see the header).
  let press: PointerPress | undefined;
  onMount(() => {
    const own = new PointerPress(window);
    press = own;
    return () => own.dispose();
  });

  function handleBlur(): void {
    const commitLeftDraft = (): void => {
      if (commitsLeftDraft(draft, document.activeElement === element)) {
        commit();
      }
    };
    if (press === undefined) {
      commitLeftDraft();
    } else {
      press.afterPress(commitLeftDraft);
    }
  }

  async function remove(index: number): Promise<void> {
    const address = recipients[index];
    if (address === undefined) {
      return;
    }
    notice = undefined;
    onremove(index);
    announce(t('components.recipientInput.removed', { address }));
    // The button is gone: the focus goes back to the input.
    await tick();
    element?.focus();
  }

  function chipKeydown(event: KeyboardEvent, index: number): void {
    if (removesChip(event.key)) {
      event.preventDefault();
      void remove(index);
    }
  }
</script>

<div class="tt-recipients {className}" class:tt-recipients--invalid={hasError}>
  <label class="tt-recipients__label" for={inputId}>
    {label}
    {#if required}<span class="tt-recipients__required">{t('components.field.required')}</span>{/if}
  </label>
  {#if hint}
    <p class="tt-recipients__hint" id={hintId}>{hint}</p>
  {/if}
  <div class="tt-recipients__box" class:tt-recipients__box--disabled={disabled}>
    {#if recipients.length > 0}
      <ul class="tt-recipients__chips" aria-label={t('components.recipientInput.list')}>
        {#each recipients as address, index (index)}
          {@const reason = chipIssues[index]}
          <li class="tt-chip" class:tt-chip--invalid={reason !== undefined}>
            {#if reason !== undefined}<Icon name="alert" size="sm" />{/if}
            <span class="tt-chip__address">{address}</span>
            {#if reason !== undefined}
              <span class="visually-hidden">{t('components.recipientInput.invalid')}</span>
            {/if}
            <button
              bind:this={removeButtons[index]}
              type="button"
              class="tt-chip__remove"
              {disabled}
              aria-label={t('components.recipientInput.remove', { address })}
              onclick={() => void remove(index)}
              onkeydown={(event) => chipKeydown(event, index)}
            >
              <span class="tt-chip__x"><Icon name="x" size="sm" /></span>
            </button>
          </li>
        {/each}
      </ul>
    {/if}
    <input
      bind:this={element}
      type="text"
      id={inputId}
      class="tt-recipients__input"
      value={draft}
      {disabled}
      inputmode="email"
      autocomplete="off"
      autocapitalize="off"
      spellcheck={false}
      aria-required={required && recipients.length === 0 ? 'true' : undefined}
      aria-invalid={hasError ? 'true' : undefined}
      aria-describedby={describedBy(hint && hintId, notice && noticeId, hasError && errorId)}
      oninput={handleInput}
      onpaste={handlePaste}
      onkeydown={handleKeydown}
      onblur={handleBlur}
    />
  </div>
  {#if notice}
    <p class="tt-recipients__notice" id={noticeId}>{notice}</p>
  {/if}
  {#if hasError}
    <div class="tt-recipients__error" id={errorId}>
      {#if error}
        <p><span class="visually-hidden">{t('components.field.errorPrefix')}</span> {error}</p>
      {/if}
      {#each refused as item, i (i)}
        <p class="tt-break">
          <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
          {t('components.recipientInput.issue', { address: item.address, reason: item.reason })}
        </p>
      {/each}
    </div>
  {/if}
</div>

