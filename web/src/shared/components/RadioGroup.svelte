<script lang="ts" generics="T extends string | number">
  // Group of native radio buttons in a fieldset with its legend (RGAA 11.5, 11.6); the hint and
  // error are linked to the fieldset.
  import { t } from '../i18n/i18n.svelte';
  import { describedBy } from './helpers';

  /** One choice of the group. */
  interface RadioOption {
    value: T;
    label: string;
    hint?: string;
    disabled?: boolean;
  }

  interface Props {
    /** Legend of the group (visible). */
    legend: string;
    /** Choices. */
    options: readonly RadioOption[];
    /** Bound selected value. */
    value?: T | undefined;
    /** Name of the radio buttons (generated by default). */
    name?: string;
    /** Help text linked to the group. */
    hint?: string;
    /** Error message; linked to the group. */
    error?: string | undefined;
    /** Required group: "(required)" in the legend and required on the inputs. */
    required?: boolean;
    /** Lays the choices out on one line when they fit. */
    inline?: boolean;
    /** Disables the whole group. */
    disabled?: boolean;
    /** Called after the selection changed. */
    onchange?: (value: T) => void;
    class?: string;
  }

  let {
    legend,
    options,
    value = $bindable(),
    name,
    hint,
    error,
    required = false,
    inline = false,
    disabled = false,
    onchange,
    class: className = '',
  }: Props = $props();

  const uid = $props.id();
  const groupName = $derived(name ?? `${uid}-radio`);
  const hintId = `${uid}-hint`;
  const errorId = `${uid}-error`;
  const invalid = $derived(error !== undefined && error !== '');
</script>

<fieldset
  class="tt-radio {className}"
  class:tt-radio--inline={inline}
  {disabled}
  aria-describedby={describedBy(hint && hintId, invalid && errorId)}
>
  <legend class="tt-radio__legend">
    {legend}
    {#if required}<span class="tt-radio__required">{t('components.field.required')}</span>{/if}
  </legend>
  {#if hint}
    <p class="tt-radio__hint" id={hintId}>{hint}</p>
  {/if}
  <div class="tt-radio__options">
    {#each options as option, index (option.value)}
      <div class="tt-radio__option">
        <input
          type="radio"
          id="{uid}-{index}"
          name={groupName}
          value={option.value}
          checked={value === option.value}
          disabled={option.disabled}
          {required}
          aria-describedby={option.hint ? `${uid}-${index}-hint` : undefined}
          onchange={() => {
            value = option.value;
            onchange?.(option.value);
          }}
        />
        <label for="{uid}-{index}">{option.label}</label>
        {#if option.hint}
          <p class="tt-radio__option-hint" id="{uid}-{index}-hint">{option.hint}</p>
        {/if}
      </div>
    {/each}
  </div>
  {#if invalid}
    <p class="tt-radio__error" id={errorId}>
      <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
      {error}
    </p>
  {/if}
</fieldset>

