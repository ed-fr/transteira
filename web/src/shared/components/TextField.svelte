<script lang="ts">
  // Labelled text input (RGAA 11.1, 11.10): visible label, optional hint, error message linked
  // by aria-describedby with aria-invalid, required state shown in the label text.
  import type { Snippet } from 'svelte';
  import type { HTMLInputAttributes } from 'svelte/elements';
  import { t } from '../i18n/i18n.svelte';
  import { describedBy } from './helpers';

  interface Props extends Omit<
    HTMLInputAttributes,
    'type' | 'value' | 'style' | 'children' | 'id' | 'aria-describedby' | 'aria-invalid'
  > {
    /** Visible label. */
    label: string;
    /** Bound value. */
    value?: string;
    /** Input type. */
    type?: 'text' | 'email' | 'password' | 'search' | 'tel' | 'url' | 'number';
    /** Element id (generated by default). */
    id?: string;
    /** Help text shown under the label and linked to the input. */
    hint?: string;
    /** Error message; sets aria-invalid and is linked to the input. */
    error?: string | undefined;
    /** Required field: native required attribute and "(required)" in the label. */
    required?: boolean;
    /** Content placed after the input in the same row (e.g. a show-password button). */
    addon?: Snippet;
    /** The input element, for focus management (e.g. focus the first invalid field). */
    element?: HTMLInputElement | undefined;
  }

  let {
    label,
    value = $bindable(''),
    type = 'text',
    id,
    hint,
    error,
    required = false,
    addon,
    element = $bindable(),
    class: className = '',
    ...rest
  }: Props = $props();

  const uid = $props.id();
  const inputId = $derived(id ?? `${uid}-input`);
  const hintId = $derived(`${inputId}-hint`);
  const errorId = $derived(`${inputId}-error`);
  const invalid = $derived(error !== undefined && error !== '');
</script>

<div class="tt-field {className}" class:tt-field--invalid={invalid}>
  <label class="tt-field__label" for={inputId}>
    {label}
    {#if required}<span class="tt-field__required">{t('components.field.required')}</span>{/if}
  </label>
  {#if hint}
    <p class="tt-field__hint" id={hintId}>{hint}</p>
  {/if}
  <div class="tt-field__row">
    <input
      {...rest}
      bind:this={element}
      bind:value
      {type}
      id={inputId}
      class="tt-field__input"
      {required}
      aria-invalid={invalid ? 'true' : undefined}
      aria-describedby={describedBy(hint && hintId, invalid && errorId)}
    />
    {#if addon}{@render addon()}{/if}
  </div>
  {#if invalid}
    <p class="tt-field__error" id={errorId}>
      <span class="visually-hidden">{t('components.field.errorPrefix')}</span>
      {error}
    </p>
  {/if}
</div>

