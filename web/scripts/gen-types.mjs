// Generates src/shared/api/schema.ts from the OpenAPI specification (../api/openapi.yaml).
//
//   node scripts/gen-types.mjs           write the file
//   node scripts/gen-types.mjs --check   fail (exit 1) if the committed file is out of date
//
// enumValues makes openapi-typescript also emit runtime arrays of every enumeration (for
// example the list of ProblemCode values used by the i18n parity tests), so the output is a
// .ts module and not a .d.ts declaration file. Only the arrays of component enumerations are
// kept: the ones derived from paths are not needed, and openapi-typescript 7.13 types those of
// path-level parameters wrongly (["parameters"]["parameters"]), which would not compile.
import { readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const spec = new URL('../../api/openapi.yaml', import.meta.url);
const out = new URL('../src/shared/api/schema.ts', import.meta.url);

const header =
  '// Code generated by scripts/gen-types.mjs from api/openapi.yaml. DO NOT EDIT.\n' +
  '// Regenerate with `make web-gen` (npm run gen).\n\n';

const ast = await openapiTS(spec, { enumValues: true, alphabetize: false });
const generated =
  header +
  astToString(ast)
    .replace(/\r\n/g, '\n')
    .split('\n')
    .filter((line) => !/^export const \w+: ReadonlyArray<FlattenedDeepRequired<paths>/.test(line))
    .join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = (await readFile(out, 'utf8')).replace(/\r\n/g, '\n');
  } catch {
    // Missing file: reported as stale below.
  }
  if (current !== generated) {
    console.error('src/shared/api/schema.ts is out of date: run `make web-gen`');
    process.exit(1);
  }
  console.log('src/shared/api/schema.ts is up to date');
} else {
  await writeFile(out, generated);
  console.log('wrote src/shared/api/schema.ts');
}
