// Caddy in front of the server under test, like a production deployment: TLS (internal CA),
// buffering disabled, long timeouts, real client IP in X-Real-IP. Runs in Docker (service
// "caddy", profile "e2e", of test/docker-compose.test.yml) and reaches the server on the host
// through host.docker.internal.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import https from 'node:https';
import path from 'node:path';
import { CLIENT_IP_HEADER } from './clientip';
import { CADDY_DIR, COMPOSE_FILE, HOSTS, HTTPS_PORT, ORIGINS } from './env';

/**
 * Caddyfile for a server listening on serverPort on the host.
 *
 * Like the reference configuration, X-Forwarded-For and X-Real-IP carry the address of the TCP
 * peer (the server reads X-Forwarded-For first). In this test proxy only, a request carrying
 * X-E2E-Client-IP (set by the browser fixtures, see clientip.ts) announces that address instead:
 * every test then has its own client IP, so the per-IP limits of the server (global rate limit,
 * verification codes per IP) do not couple parallel tests, and a test can simulate a client
 * outside the internal ranges. The header itself is never forwarded to the server.
 */
export function caddyfile(serverPort: number): string {
  const upstream = (realIp: string) => `reverse_proxy host.docker.internal:${serverPort} {
			header_up X-Forwarded-For ${realIp}
			header_up X-Real-IP ${realIp}
			header_up -${CLIENT_IP_HEADER}
			flush_interval -1
			transport http {
				read_timeout 0
				write_timeout 0
			}
		}`;
  return `# Generated by test/e2e/support/caddy.ts for one end-to-end run. Do not edit.
{
	local_certs
	auto_https disable_redirects
	admin off
}

${HOSTS.admin}, ${HOSTS.a}, ${HOSTS.b} {
	tls internal
	@simulated header_regexp ${CLIENT_IP_HEADER} ^[0-9A-Fa-f:.]{2,45}$
	handle @simulated {
		${upstream(`{http.request.header.${CLIENT_IP_HEADER}}`)}
	}
	handle {
		${upstream('{remote_host}')}
	}
}
`;
}

function compose(args: string[]): void {
  execFileSync('docker', ['compose', '-f', COMPOSE_FILE, '--profile', 'e2e', ...args], {
    stdio: ['ignore', 'pipe', 'pipe'],
    env: { ...process.env, E2E_HTTPS_PORT: String(HTTPS_PORT) },
  });
}

/** Writes the Caddyfile, (re)creates the Caddy container and waits until it proxies. */
export async function startCaddy(serverPort: number): Promise<void> {
  fs.mkdirSync(CADDY_DIR, { recursive: true });
  fs.writeFileSync(path.join(CADDY_DIR, 'Caddyfile'), caddyfile(serverPort));
  // --force-recreate: a container left by an earlier run would keep the previous port.
  compose(['up', '-d', '--force-recreate', 'caddy']);
  await waitProxied();
}

/** Polls the admin host through Caddy until the server answers /healthz. */
async function waitProxied(timeoutMs = 30_000): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  let last = 'no answer';
  while (Date.now() < deadline) {
    // Caddy's internal CA is not trusted by Node: this loopback readiness probe skips verification.
    last = await new Promise<string>((resolve) => {
      // Connect to loopback (where Chromium resolves *.localhost) with the admin host as SNI and Host.
      const req = https.get(
        {
          host: '127.0.0.1',
          port: HTTPS_PORT,
          path: '/healthz',
          servername: HOSTS.admin,
          headers: { Host: new URL(ORIGINS.admin).host },
          rejectUnauthorized: false,
          timeout: 2_000,
        },
        (res) => {
          res.resume();
          resolve(String(res.statusCode));
        },
      );
      req.on('timeout', () => req.destroy(new Error('timeout')));
      req.on('error', (e) => resolve(e.message));
    });
    if (last === '200') return;
    await new Promise((r) => setTimeout(r, 300));
  }
  throw new Error(`Caddy does not proxy to the server after ${timeoutMs} ms (last: ${last})`);
}

/** Stops and removes the Caddy container (ignores a container that is already gone). */
export function stopCaddy(): void {
  try {
    compose(['rm', '--stop', '--force', 'caddy']);
  } catch {
    // nothing to stop
  }
}
